"""Ricostruisce solo eic_magazzino_integrato da metadati letti, mai il servizio online."""
import json,re,collections
from db import *

def build():
 m=load('schema-ready.json');functions=load('functions-ready.json')+load('aux-functions.json');report={'tables':len(m['tables']),'functions':len(functions),'policies':len(m['policies']),'substitutions':[]}
 sql("DO $$ BEGIN IF current_database()<>'eic_magazzino_integrato' THEN RAISE EXCEPTION 'Database locale richiesto'; END IF; END $$;DROP SCHEMA IF EXISTS public CASCADE;DROP SCHEMA IF EXISTS auth CASCADE;DROP SCHEMA IF EXISTS private CASCADE;CREATE SCHEMA public;CREATE SCHEMA auth;CREATE SCHEMA private;CREATE SCHEMA IF NOT EXISTS extensions;CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\" WITH SCHEMA extensions;CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA extensions;")
 sql('GRANT USAGE ON SCHEMA public,auth TO authenticated,anon;')
 enums=collections.defaultdict(list)
 for e in m['enums']:enums[(e['schema'],e['name'])].append(e)
 for (schema,name),es in enums.items():sql(f'CREATE TYPE {ident(schema)}.{ident(name)} AS ENUM('+','.join(lit(e['label']) for e in sorted(es,key=lambda e:e['sort']))+')')
 cols=collections.defaultdict(list)
 for c in m['columns']:cols[(c['schema'],c['table'])].append(c)
 def table(c):return ident(c['schema'])+'.'+ident(c.get('table') or c['name'])
 seq=set()
 for c in m['columns']:
  for name in re.findall(r"nextval\('([^']+)'",c['default'] or ''):seq.add(name)
 for name in sorted(seq):sql('CREATE SEQUENCE IF NOT EXISTS '+name)
 for t in m['tables']:
  lines=[]
  for c in sorted(cols[(t['schema'],t['name'])],key=lambda c:c['position']):
   typ=c['type']
   if typ.startswith('vector('):
    typ='text';report['substitutions'].append({'table':t['name'],'column':c['name'],'from':c['type'],'to':'text','reason':'embedding fuori dal percorso Magazzino; pgvector non installato nel PostgreSQL locale'})
   line=ident(c['name'])+' '+typ
   if c['generated']:line+=' GENERATED ALWAYS AS ('+c['default']+') STORED'
   elif c['identity']:line+=' GENERATED BY DEFAULT AS IDENTITY'
   if c['notnull']:line+=' NOT NULL'
   lines.append(line)
  sql('SET search_path=public,extensions,auth;CREATE TABLE '+table(t)+'('+','.join(lines)+')')
 sql("CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),(nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub'))::uuid $$;CREATE OR REPLACE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS $$ SELECT coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;CREATE OR REPLACE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$ SELECT auth.jwt()->>'role' $$;")
 pending_functions=[]
 for f in functions:
  try:sql('SET check_function_bodies=off;SET search_path=public,extensions,auth;'+f['definition'])
  except DbError as e:
   if '42704' not in str(e):raise
   pending_functions.append(f)
 pending=list(m['views'] or [])
 while pending:
  rest=[];errors=[]
  for v in pending:
   try:sql('SET search_path=public,extensions,auth;CREATE VIEW '+table(v)+((' WITH ('+','.join(v['options'])+')') if v['options'] else '')+' AS '+v['definition'])
   except DbError as e:rest.append(v);errors.append(str(e))
  if len(rest)==len(pending):raise DbError('Dipendenze viste non risolte: '+str(errors))
  pending=rest
 for f in pending_functions:sql('SET check_function_bodies=off;SET search_path=public,extensions,auth;'+f['definition'])
 for c in m['columns']:
  if c['default'] and not c['generated'] and not c['identity']:sql('SET search_path=public,extensions,auth;ALTER TABLE '+table(c)+' ALTER COLUMN '+ident(c['name'])+' SET DEFAULT '+c['default'])
 for typ in ['p','u','c','x']:
  for c in m['constraints']:
   if c['type']==typ:sql('SET search_path=public,extensions,auth;ALTER TABLE '+table(c)+' ADD CONSTRAINT '+ident(c['name'])+' '+c['definition'])
 for c in m['constraints']:
  if c['type']=='f':sql('ALTER TABLE '+table(c)+' ADD CONSTRAINT '+ident(c['name'])+' '+re.sub(r'\s+NOT VALID$','',c['definition'])+' NOT VALID')
 finish(m,report)

def finish(m,report):
 def table(c):return ident(c['schema'])+'.'+ident(c.get('table') or c['name'])
 for i in m['indexes']:
  if re.search(r'USING (?:hnsw|ivfflat)',i['definition']):report['substitutions'].append({'index':i['definition'].split(' ON ')[0],'reason':'indice vettoriale fuori perimetro'});continue
  sql('SET search_path=public,extensions,auth;'+i['definition'].replace('CREATE INDEX ','CREATE INDEX IF NOT EXISTS ').replace('CREATE UNIQUE INDEX ','CREATE UNIQUE INDEX IF NOT EXISTS '))
 extra=load('fattura-ordine.json')
 if not sql("SELECT to_regclass('public.fattura_ordine') IS NOT NULL"):
  fields=[]
  for c in sorted(extra['columns'],key=lambda x:x['position']):
   fields.append(ident(c['name'])+' '+c['type']+(' NOT NULL' if c['notnull'] else '')+(' DEFAULT '+c['default'] if c['default'] else ''))
  sql('CREATE TABLE public.fattura_ordine('+','.join(fields)+')')
  for c in extra['constraints']:sql('ALTER TABLE public.fattura_ordine ADD CONSTRAINT '+ident(c['name'])+' '+c['definition'])
  sql('ALTER TABLE public.fattura_ordine ENABLE ROW LEVEL SECURITY;REVOKE ALL ON public.fattura_ordine FROM PUBLIC,anon,authenticated;')
 report['tables']+=1
 # Riproduce ACL reali dei ruoli API; il proprietario locale resta il ruolo amministrativo.
 def apply_acl(kind,obj,acl):
  sql('REVOKE ALL ON '+kind+' '+obj+' FROM PUBLIC,anon,authenticated')
  if not acl:return
  rights={'r':'SELECT','a':'INSERT','w':'UPDATE','d':'DELETE','D':'TRUNCATE','x':'REFERENCES','t':'TRIGGER','X':'EXECUTE'}
  for part in acl.strip('{}').split(','):
   role,_,grants=part.partition('=');grants=grants.partition('/')[0];role=role.strip('"')
   if role not in ('','anon','authenticated'):continue
   privileges=[name for key,name in rights.items() if key in grants]
   if privileges:sql('GRANT '+','.join(privileges)+' ON '+kind+' '+obj+' TO '+('PUBLIC' if not role else ident(role)))
 for t in m['tables']:
  apply_acl('TABLE',table(t),t['acl'])
  if t['rls']:sql('ALTER TABLE '+table(t)+' ENABLE ROW LEVEL SECURITY')
  if t['force_rls']:sql('ALTER TABLE '+table(t)+' FORCE ROW LEVEL SECURITY')
 for v in m['views']:apply_acl('TABLE',table(v),v['acl'])
 for p in m['policies']:
  roles=p['roles'] if isinstance(p['roles'],list) else p['roles'].strip('{}').split(',');statement='CREATE POLICY '+ident(p['policyname'])+' ON public.'+ident(p['tablename'])+' AS '+p['permissive']+' FOR '+p['cmd']+' TO '+','.join('PUBLIC' if r=='public' else ident(r) for r in roles)
  if p['qual']:statement+=' USING ('+p['qual']+')'
  if p['with_check']:statement+=' WITH CHECK ('+p['with_check']+')'
  sql('DROP POLICY IF EXISTS '+ident(p['policyname'])+' ON public.'+ident(p['tablename'])+';'+statement)
 for f in load('aux-functions.json'):
  apply_acl('FUNCTION',ident(f['nspname'])+'.'+ident(f['proname'])+'('+f['identity']+')',f['proacl'])
 for f in m['functions_acl']:apply_acl('FUNCTION',ident(f['schema'])+'.'+ident(f['name'])+'('+f['identity']+')',f['acl'])
 # Trigger esatti del percorso operativo, inclusi audit e automazioni dei costi.
 triggers=json.loads((ROOT/'docs/ux/magazzino-riconciliazione/triggers.json').read_text())+json.loads((ROOT/'docs/ux/magazzino-riconciliazione/extra-triggers.json').read_text())
 for t in triggers:sql('DROP TRIGGER IF EXISTS '+ident(t['tgname'])+' ON public.'+ident(t['relname'])+';'+t['definition'])
 report['triggers']=len(triggers)
 REPORT.mkdir(parents=True,exist_ok=True);(REPORT/'schema-build.json').write_text(json.dumps(report,indent=2)+'\n')
 print(json.dumps({'schema_built':True,'tables':report['tables'],'functions':report['functions'],'triggers':len(triggers),'policies':report['policies']}))
if __name__=='__main__':
 import sys
 if '--finish' in sys.argv:
  functions=load('functions-ready.json')+load('aux-functions.json');m=load('schema-ready.json')
  for f in functions:sql('SET check_function_bodies=off;SET search_path=public,extensions,auth;'+f['definition'])
  finish(m,{'tables':len(m['tables']),'functions':len(functions),'policies':len(m['policies']),'substitutions':['4 colonne embedding e indici vettoriali esclusi dal perimetro funzionale']})
 else:build()
