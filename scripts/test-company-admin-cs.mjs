import { createRequire } from 'node:module';
import { readFileSync, readdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const { PGlite } = createRequire(import.meta.url)('@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth;
 create table auth.users(id uuid primary key); create type public.app_role as enum ('super_admin');
 create function auth.uid() returns uuid language sql as 'select null::uuid';
 create function public.has_role(uuid, public.app_role) returns boolean language sql as $$select coalesce(current_setting('test.is_admin', true),'false')='true'$$;
 create table public.companies(id uuid primary key);
 insert into public.companies values ('00000000-0000-4000-a000-000000000001');
 grant usage on schema public,auth to authenticated;
`);
const dir = new URL('../supabase/migrations/', import.meta.url);
const name = readdirSync(dir).find(file => file.endsWith('_company_admin_onboarding_communications.sql'));
const sql = readFileSync(new URL(name, dir), 'utf8');
await db.exec(sql);
await db.exec(sql); // Riapplicazione sicura: nessuna duplicazione né task/invii automatici.
const { rows } = await db.query(`select count(*)::int as n from onboarding_task`);
assert.equal(rows[0].n, 0);
await db.exec('set role anon');
await assert.rejects(db.query('select * from onboarding_task'), /permission denied/);
await db.exec('reset role; set role authenticated');
await assert.rejects(db.exec(`insert into onboarding_task(company_id,titolo) values ('00000000-0000-4000-a000-000000000001','Avvio')`), /row-level security/);
await assert.rejects(db.exec(`insert into superadmin_comunicazioni(company_id,tipo,corpo) values ('00000000-0000-4000-a000-000000000001','email','Test')`), /row-level security/);
await db.exec(`set test.is_admin = 'true'; insert into onboarding_task(company_id,titolo) values ('00000000-0000-4000-a000-000000000001','Avvio');
 insert into superadmin_comunicazioni(company_id,tipo,corpo) values ('00000000-0000-4000-a000-000000000001','email','Contatto annotato');`);
assert.equal((await db.query('select * from onboarding_task')).rows.length, 1);
await assert.rejects(db.exec(`update onboarding_task set stato='non_valido'`), /check constraint/);
await db.exec(`update onboarding_task set stato='completato',completato_at=now(); update onboarding_task set stato='da_fare',completato_at=null;`);
assert.equal((await db.query('select completato_at from onboarding_task')).rows[0].completato_at,null);
await db.exec(`set test.is_admin = 'false'`);
assert.equal((await db.query('select * from onboarding_task')).rows.length,0);
assert.equal((await db.query('select * from superadmin_comunicazioni')).rows.length,0);
await db.close();
console.log('9 verifiche PostgreSQL superate: migrazione idempotente, nessun invio/task automatico, accessi CS riservati, stati e riapertura task.');
