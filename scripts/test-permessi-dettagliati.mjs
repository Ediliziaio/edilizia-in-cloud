import { readFileSync, readdirSync } from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";
import { PGlite } from "@electric-sql/pglite";

const source = readFileSync("supabase/functions/_shared/staffPermissionsDefaults.ts", "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { STAFF_PERMISSION_DEFAULTS } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
const bools = Object.keys(STAFF_PERMISSION_DEFAULTS).filter(k => typeof STAFF_PERMISSION_DEFAULTS[k] === "boolean" && k !== "permessi_dettagliati");
const db = new PGlite();
const u = "00000000-0000-0000-0000-000000000001";
const c = "00000000-0000-0000-0000-000000000010";
const other = "00000000-0000-0000-0000-000000000011";
const crmTables = ['marketing_contacts','marketing_contact_activities','marketing_contact_notes','marketing_contact_lists','marketing_documents','marketing_tags','marketing_opportunities','marketing_opportunity_notes','marketing_pipelines','marketing_pipeline_stages','marketing_calendars','marketing_calendar_availability','marketing_calendar_preferences','marketing_custom_fields'];
await db.exec(`
 create schema auth; create role authenticated; create role anon; create role service_role;
 create type app_role as enum ('company_admin','company_staff','super_admin');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create function has_role(uuid,app_role) returns bool language sql stable as $$select false$$;
 create function utente_bloccato() returns bool language sql stable as $$select false$$;
 create table profiles(id uuid,company_id uuid);
 create table multi_company_access(user_id uuid,company_id uuid,status text,access_role text,expires_at timestamptz);
 create table staff_permissions(user_id uuid,company_id uuid, ${bools.map(k => `"${k}" boolean not null default ${STAFF_PERMISSION_DEFAULTS[k]}`).join(",")}, primary key(user_id,company_id));
`);
await db.exec(crmTables.map(t => `create table ${t}(id int,company_id uuid)`).join(';'));
const helpers = readFileSync("supabase/migrations/20280903260000_marketing_policy_permessi_una_volta.sql", "utf8");
await db.exec(helpers.slice(helpers.indexOf("CREATE OR REPLACE FUNCTION public.aziende_con_permesso"), helpers.indexOf("COMMENT ON FUNCTION")));
const files = readdirSync("supabase/migrations").filter(f => f.endsWith("_permessi_lettura_modifica_distinti.sql"));
assert.equal(files.length, 1);
const migration = readFileSync(`supabase/migrations/${files[0]}`, "utf8");
await db.exec(migration); await db.exec(migration);
await db.exec(`create trigger trg_permessi before insert or update on staff_permissions for each row execute function permessi_modifica_segue_visibilita();`);
await db.exec(`insert into staff_permissions(user_id,company_id,can_view_orders,can_view_operai) values ('${u}','${c}',true,true)`);
let row = (await db.query(`select * from staff_permissions where user_id='${u}'`)).rows[0];
assert.equal(row.can_edit_orders, true, "La modalità preesistente conserva la modifica automatica");
await db.exec(`update staff_permissions set permessi_dettagliati=true,can_edit_orders=false,can_edit_operai=false,can_view_giornale_lavori=true,can_edit_giornale_lavori=true where user_id='${u}'`);
row = (await db.query(`select * from staff_permissions where user_id='${u}'`)).rows[0];
assert.equal(row.can_edit_orders, false);
assert.equal(row.can_edit_operai, false);
assert.equal(row.can_edit_giornale_lavori, true);

// Usa il vero risolutore dei permessi, insieme alle stesse condizioni delle
// policy per verificare letture, scritture e isolamento con ruolo authenticated.
await db.exec(`
 create table orders(id int,company_id uuid); create table rapportini(id int,company_id uuid); create table operai(id int,company_id uuid);
 insert into orders values(1,'${c}'),(2,'${other}');
 alter table orders enable row level security; alter table rapportini enable row level security; alter table operai enable row level security;
 create policy leggi on orders for select to authenticated using(company_id=any(aziende_con_permesso('can_view_orders')));
 create policy scrivi on orders for insert to authenticated with check(company_id=any(aziende_con_permesso('can_edit_orders')));
 create policy scrivi on rapportini for insert to authenticated with check(company_id=any(aziende_con_permesso('can_edit_giornale_lavori')));
 create policy scrivi on operai for insert to authenticated with check(company_id=any(aziende_con_permesso('can_edit_operai')));
 alter table marketing_contacts enable row level security;
 create policy commesse_legacy on marketing_contacts for select to authenticated using(company_id=any(aziende_con_permesso('can_view_orders')));
 insert into marketing_contacts values(1,'${c}'),(2,'${other}');
 alter table staff_permissions enable row level security;
 create policy miei_permessi on staff_permissions for select to authenticated using(user_id=auth.uid());
 grant usage on schema public,auth to authenticated;
 grant select,insert,update on orders,rapportini,operai,staff_permissions,marketing_contacts to authenticated;
 select set_config('request.jwt.claim.sub','${u}',false); set role authenticated;
`);
assert.equal((await db.query("select count(*)::int n from orders")).rows[0].n, 1);
assert.equal((await db.query("select count(*)::int n from marketing_contacts")).rows[0].n, 0, "Le commesse non aprono il CRM in modalità distinta");
assert.equal((await db.query("select has_function_privilege('anon','public.aziende_con_permessi_dettagliati()','execute') ok")).rows[0].ok, false);
await db.exec(`reset role; update staff_permissions set can_view_marketing_contacts=true where user_id='${u}'; set role authenticated`);
assert.equal((await db.query("select count(*)::int n from marketing_contacts")).rows[0].n, 1, "Un permesso CRM esplicito consente la lettura nella sola società concessa");
await db.exec(`reset role; update staff_permissions set permessi_dettagliati=false,can_view_marketing_contacts=false where user_id='${u}'; set role authenticated`);
assert.equal((await db.query("select count(*)::int n from marketing_contacts")).rows[0].n, 1, "Gli altri utenti mantengono le regole precedenti");
await db.exec(`reset role; update staff_permissions set permessi_dettagliati=true,can_edit_orders=false,can_edit_operai=false where user_id='${u}'; set role authenticated`);
await assert.rejects(db.exec(`insert into orders values(3,'${c}')`), e => e.code === "42501");
await assert.rejects(db.exec(`insert into operai values(1,'${c}')`), e => e.code === "42501");
await db.exec(`insert into rapportini values(1,'${c}')`);
await assert.rejects(db.exec(`insert into rapportini values(2,'${other}')`), e => e.code === "42501");
assert.equal((await db.query("update staff_permissions set can_edit_orders=true returning user_id")).rows.length, 0, "Lo staff non può assegnarsi permessi");
await db.exec(`reset role; update staff_permissions set sola_lettura=true,can_edit_orders=true,can_edit_giornale_lavori=true,can_manage_payments=true,can_approve_variations=true,can_manage_condizioni=true where user_id='${u}';`);
row = (await db.query(`select * from staff_permissions where user_id='${u}'`)).rows[0];
for (const key of ["can_edit_orders", "can_edit_giornale_lavori", "can_manage_payments", "can_approve_variations", "can_manage_condizioni"]) assert.equal(row[key], false, key);
await db.exec("set role authenticated");
await assert.rejects(db.exec(`insert into rapportini values(3,'${c}')`), e => e.code === "42501");
await db.close();
console.log("Permessi distinti: compatibilità, rapportini senza modifica commesse/operai, isolamento, niente autoassegnazione e sola lettura OK.");
