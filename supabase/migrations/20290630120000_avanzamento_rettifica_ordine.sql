-- La rettifica deve vincere davvero: i movimenti si mettono in fila con un numero, non con l'ora
-- ───────────────────────────────────────────────────────────────────────────────────────────────
-- 28/11/2026, dalla prova in transazione annullata del lotto 1.
--
-- La percentuale derivata è «la più alta dichiarata, salvo una rettifica dell'ufficio che azzera
-- quello di prima». Per sapere che cosa viene «dopo la rettifica» la funzione guardava `created_at`.
-- Ma `now()` in Postgres è l'ora dell'INIZIO DELLA TRANSAZIONE: due movimenti scritti nella stessa
-- transazione hanno lo stesso identico istante, e il confronto `created_at >= rettifica` li prende
-- tutti — compresi quelli che la rettifica doveva cancellare. Nella prova: 60, poi 20, poi una
-- rettifica a 30, e il risultato restava 60.
--
-- Non è un caso di laboratorio: una funzione che scrive più movimenti insieme (il rendiconto che
-- prende le voci di più rapportini, il travaso dei saldi di apertura) sta in una transazione sola.
--
-- Qui i movimenti prendono un numero progressivo, che non dipende dall'orologio: `seq`. La
-- rettifica è «da quel numero in poi», e il comportamento è lo stesso dentro e fuori la transazione.
-- Idempotente.

alter table public.avanzamento_movimenti
  add column if not exists seq bigint generated by default as identity;

create index if not exists avanzamento_movimenti_seq_idx
  on public.avanzamento_movimenti (sottofase_id, seq) where sottofase_id is not null;

grant select (seq) on public.avanzamento_movimenti to authenticated;

create or replace function private.avanzamento_derivato_sottofase(p_sottofase uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_s record; v_tot numeric; v_q numeric; v_pct numeric; v_da bigint;
begin
  select s.id, s.modo_avanzamento, s.quantita_contratto, s.percentuale, s.quantita_fatta
    into v_s from public.order_work_subphases s where s.id = p_sottofase;
  if not found then return null; end if;
  v_tot := coalesce(v_s.quantita_contratto, public.sottofase_quantita_totale(p_sottofase));

  if coalesce(v_s.modo_avanzamento, 'quantita') = 'quantita' and v_tot is not null and v_tot > 0 then
    select round(coalesce(sum(m.quantita), 0), 3) into v_q
      from public.avanzamento_movimenti m
     where m.sottofase_id = p_sottofase and m.modo = 'quantita';
    v_q := least(greatest(v_q, 0), v_tot);
    v_pct := case when v_q <= 0 then 0
                  when v_q >= v_tot then 100
                  else greatest(1, least(99, round(100 * v_q / v_tot))) end;
    return jsonb_build_object('quantita', v_q, 'percentuale', v_pct, 'base', v_tot);
  end if;

  -- A percentuale: vince la più alta dichiarata. Una rettifica azzera quello che c'era prima di lei,
  -- e da lì in poi si torna a contare (la rettifica stessa compresa).
  select max(m.seq) into v_da
    from public.avanzamento_movimenti m
   where m.sottofase_id = p_sottofase and m.modo = 'percentuale' and m.rettifica;
  select coalesce(max(m.percentuale), 0) into v_pct
    from public.avanzamento_movimenti m
   where m.sottofase_id = p_sottofase and m.modo = 'percentuale'
     and (v_da is null or m.seq >= v_da);
  return jsonb_build_object('quantita', null, 'percentuale', round(v_pct), 'base', v_tot);
end;
$function$;
